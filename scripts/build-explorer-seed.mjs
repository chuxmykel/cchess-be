// Builds src/explorer/seed-positions.ts - the positions the opening explorer
// keeps from lichess before anyone asks (see README, "Opening explorer") -
// from lichess's opening list (github.com/lichess-org/chess-openings, CC0),
// pinned to the commit ../cchess's scripts/build-openings.js reads, so the
// book the app names is the book the server keeps:
//   node scripts/build-explorer-seed.mjs
// Every position along each line counts, not only the named one it reaches:
// the explorer is stepped through move by move. Keyed by EPD (a FEN's first
// four fields), as moves.positionKey is.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { Chess } from 'chess.js';

const COMMIT = '712a58be746c143f4ab935b68acc50f4bac813eb';
const BASE = `https://raw.githubusercontent.com/lichess-org/chess-openings/${COMMIT}`;
const OUT = fileURLToPath(
  new URL('../src/explorer/seed-positions.ts', import.meta.url),
);

const epd = (fen) => fen.split(' ').slice(0, 4).join(' ');

const positions = new Set();
for (const volume of ['a', 'b', 'c', 'd', 'e']) {
  const response = await fetch(`${BASE}/${volume}.tsv`);
  if (!response.ok) throw new Error(`${volume}.tsv: ${response.status}`);
  const rows = (await response.text()).trim().split('\n').slice(1);
  for (const row of rows) {
    const pgn = row.split('\t')[2];
    const line = new Chess();
    line.loadPgn(pgn);
    const replay = new Chess();
    positions.add(epd(replay.fen()));
    for (const move of line.history()) {
      replay.move(move);
      positions.add(epd(replay.fen()));
    }
  }
}

const sorted = [...positions].sort();
writeFileSync(
  OUT,
  `// Generated by scripts/build-explorer-seed.mjs - don't edit by hand.\n` +
    `// Every position along lichess's named openings (chess-openings@${COMMIT.slice(0, 7)}, CC0), by EPD.\n` +
    `export const SEED_POSITIONS: readonly string[] = ${JSON.stringify(sorted, null, 0)};\n`,
);
console.log(`${sorted.length} positions -> ${OUT}`);
